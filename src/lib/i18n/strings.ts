export const STRINGS: Record<Lang, Strings> = { de, en };

/** Label for a review field path such as "seller.city" or "lines.2.unitPrice". */
export function fieldLabel(s: Strings, path: string): string {
  const key = path.split(".").at(-1) as keyof Strings["fields"];
  return s.fields[key] ?? path;
}
