/**
 * Compatibility overrides for known SaxonJS limitations. The official XSLT files stay
 * byte-for-byte unchanged: for an affected stylesheet we compile a small wrapper that
 * `xsl:import`s the official file and redefines ONE function with higher import precedence.
 *
 * Every shim pins the exact original function text. If KoSIT changes that function in a later
 * release, the build fails and the shim has to be reviewed. The parity job against the Java
 * validator is what proves each shim correct.
 *
 * Shim 1, xr:checkIBAN (rules BR-DE-19, BR-DE-20):
 *   The official function computes the IBAN mod-97 check with
 *   `xs:integer(<24+ digit string>) mod 97`. Saxon-HE (Java) evaluates xs:integer with
 *   arbitrary precision. SaxonJS 2.7 stores xs:integer as an IEEE double, so digits beyond 2^53
 *   are lost and the check gives wrong answers for some valid IBANs (found by the parity job:
 *   ZUGFeRD corpus "XRECHNUNG_Elektron", IBAN DE91100000000123456789). The override uses
 *   xs:decimal, which SaxonJS implements with arbitrary precision. For integral input the
 *   mathematical result is identical.
 */
export type Shim = {
  id: string;
  /** Applies to stylesheets whose repository location matches. */
  appliesTo: RegExp;
  /** Exact original text that must be present in the official file (guards against drift). */
  original: string;
  /** Namespace declarations the override needs. */
  namespaces: Record<string, string>;
  /** Replacement xsl:function element. */
  override: string;
};

const IBAN_ORIGINAL =
  `<xsl:sequence select="matches($normalizedIban, $XR-IBAN-REGEX) and                           xs:integer(string-join(for $cp in string-to-codepoints(concat(substring($normalizedIban,5),upper-case(substring($normalizedIban,1,2)),substring($normalizedIban,3,2))) return (if($cp &gt; 64) then string($cp - 55) else string($cp - 48)),'')) mod 97 = 1"/>`;

export const SHIMS: Shim[] = [
  {
    id: "xr-checkIBAN-decimal",
    appliesTo: /xrechnung\/3\.0\.2\/xsl\/XRechnung-(UBL|CII)-validation\.xsl$/,
    original: IBAN_ORIGINAL,
    namespaces: { xr: "xrechnung", xs: "http://www.w3.org/2001/XMLSchema" },
    override: `<xsl:function name="xr:checkIBAN" as="xs:boolean">
    <xsl:param name="iban" as="xs:string"/>
    <xsl:variable name="normalizedIban" select="normalize-space(replace($iban, '([\\s])', ''))"/>
    <xsl:sequence select="matches($normalizedIban, $XR-IBAN-REGEX) and xs:decimal(string-join(for $cp in string-to-codepoints(concat(substring($normalizedIban,5),upper-case(substring($normalizedIban,1,2)),substring($normalizedIban,3,2))) return (if($cp &gt; 64) then string($cp - 55) else string($cp - 48)),'')) mod 97 = 1"/>
  </xsl:function>`,
  },
];

/** Builds the wrapper stylesheet for `officialFileUrl`, or returns null if no shim applies. */
export function wrapperFor(location: string, officialText: string, officialFileUrl: string): string | null {
  const shims = SHIMS.filter((s) => s.appliesTo.test(location));
  if (shims.length === 0) return null;
  for (const s of shims) {
    if (!officialText.includes(s.original)) {
      throw new Error(`shim ${s.id}: original function text not found in ${location}; review the shim`);
    }
  }
  const ns = Object.assign({}, ...shims.map((s) => s.namespaces)) as Record<string, string>;
  const decls = Object.entries(ns)
    .map(([p, u]) => `xmlns:${p}="${u}"`)
    .join(" ");
  return `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/rules/shims.ts. Imports the official file unchanged and overrides: ${shims.map((s) => s.id).join(", ")} -->
<xsl:stylesheet version="3.0" xmlns:xsl="http://www.w3.org/1999/XSL/Transform" ${decls}>
  <xsl:import href="${officialFileUrl}"/>
  ${shims.map((s) => s.override).join("\n  ")}
</xsl:stylesheet>
`;
}
